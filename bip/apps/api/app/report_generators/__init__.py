class CollectorStatusGenerator(BaseReportGenerator):
    """Reports on collector freshness.

    Collector health is inferred from the freshness of machine heartbeats
    (``last_seen``) relative to the platform freshness window.
    """

    def get_report_type(self) -> ReportType:
        return ReportType.COLLECTOR_STATUS

    async def generate(
        self, context: ReportGenerationContext, generated_by: str
    ) -> ReportDocument:
        sections = self._base_sections(context, ReportType.COLLECTOR_STATUS)

        from datetime import datetime, timezone

        now = datetime.now(timezone.utc)
        fresh_machines: List[Dict[str, Any]] = []
        stale_machines: List[Dict[str, Any]] = []
        for machine in context.machines:
            last_seen = machine.last_seen
            if last_seen is not None and last_seen.tzinfo is None:
                last_seen = last_seen.replace(tzinfo=timezone.utc)
            delta_seconds = (now - last_seen).total_seconds() if last_seen is not None else None
            row = {
                "machine_id": machine.id,
                "name": machine.name,
                "last_seen": machine.last_seen.isoformat() if machine.last_seen else "never",
                "age_seconds": delta_seconds,
            }
            if delta_seconds is not None and delta_seconds <= 60:
                fresh_machines.append(row)
            else:
                stale_machines.append(row)

        sections.append(
            self._metrics(
                "collector-status-summary",
                "Collector Status",
                [
                    {"label": "Machines Reporting", "value": len(fresh_machines), "unit": "count"},
                    {"label": "Machines Stale", "value": len(stale_machines), "unit": "count"},
                    {"label": "Timeline Events", "value": len(context.timeline_events), "unit": "count"},
                ],
            )
        )
        if context.machines:
            sections.append(
                self._table(
                    "collector-status-fresh",
                    "Machines Reporting (last 60s)",
                    [r for r in self._machine_rows(context) if r["machine_id"] in {m["machine_id"] for m in fresh_machines}],
                )
            )
            if stale_machines:
                sections.append(
                    self._table(
                        "collector-status-stale",
                        "Machines Not Reporting",
                        [r for r in self._machine_rows(context) if r["machine_id"] in {m["machine_id"] for m in stale_machines}],
                    )
                )
        else:
            sections.append(
                self._summary(
                    "collector-status-no-data",
                    "No Collector Data",
                    "No machine heartbeats are currently available from the collector.",
                )
            )
        sections.append(
            self._chart_placeholder(
                "collector-status-chart",
                "Collector Heartbeats",
                "Chart placeholder: collector heartbeat recency over the selected range.",
            )
        )
        sections.append(self._footer(context, ReportType.COLLECTOR_STATUS))
        return self._document(
            context, "Collector Status", ReportType.COLLECTOR_STATUS, sections, generated_by
        )


# Registry for report generators                                          # noqa: E266
class ReportGeneratorRegistry:
    """Registry mapping every supported report type to its generator."""

    def __init__(self) -> None:
        self._generators: Dict[ReportType, BaseReportGenerator] = {}

    def register(self, generator: BaseReportGenerator) -> None:
        self._generators[generator.get_report_type()] = generator

    def get_generator(self, report_type: ReportType) -> BaseReportGenerator:
        if report_type not in self._generators:
            raise ValueError(f"No generator registered for report type: {report_type}")
        return self._generators[report_type]

    def get_supported_types(self) -> List[ReportType]:
        return list(self._generators.keys())

    @staticmethod
    def create_default_registry() -> "ReportGeneratorRegistry":
        registry = ReportGeneratorRegistry()
        for generator in [
            ExecutiveSummaryGenerator(),
            MachinePerformanceGenerator(),
            BatterySummaryGenerator(),
            BatteryLifecycleGenerator(),
            QualitySummaryGenerator(),
            AnalyticsSummaryGenerator(),
            TimelineReportGenerator(),
            OperationsSummaryGenerator(),
            SystemHealthGenerator(),
            CollectorStatusGenerator(),
        ]:
            registry.register(generator)
        return registry