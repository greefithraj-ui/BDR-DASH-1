"""Report generators for the Battery Intelligence Platform.

Each generator consumes a :class:`ReportGenerationContext` — a snapshot of live
data already fetched by :class:`ReportService` through the existing
repositories. Generators never touch SQL and never call back into the API; they
only map the in-memory context into a :class:`ReportDocument`.

Shared layout logic lives on :class:`BaseReportGenerator` so that every report
type gets the mandated structure (title, generated timestamp, time range,
filters applied, summary, metrics, tables, chart placeholders, footer) without
duplicating code.
"""

from abc import ABC, abstractmethod
from datetime import datetime
from typing import Any, Dict, List
from uuid import uuid4

from app.models.report import (
    ReportDocument,
    ReportGenerationContext,
    ReportMetadata,
    ReportSection,
    ReportSectionType,
    ReportType,
    TimeRange,
)


class BaseReportGenerator(ABC):
    """Abstract base class for all report generators."""

    @abstractmethod
    def get_report_type(self) -> ReportType:
        """Return the report type this generator produces."""

    @abstractmethod
    async def generate(
        self, context: ReportGenerationContext, generated_by: str
    ) -> ReportDocument:
        """Generate a report document from the given live-data context."""

    # ------------------------------------------------------------------
    # Shared section/document builders (reused by every generator)
    # ------------------------------------------------------------------

    def _time_range(self, context: ReportGenerationContext) -> TimeRange:
        filters = context.filters
        return TimeRange(
            start=filters.date_from or datetime.min,
            end=filters.date_to or datetime.max,
        )

    def _metrics(
        self, section_id: str, title: str, rows: List[Dict[str, Any]]
    ) -> ReportSection:
        return ReportSection(
            id=section_id,
            type=ReportSectionType.METRICS,
            title=title,
            data={"metrics": rows},
        )

    def _table(
        self, section_id: str, title: str, rows: List[Dict[str, Any]]
    ) -> ReportSection:
        return ReportSection(
            id=section_id,
            type=ReportSectionType.TABLE,
            title=title,
            data={"rows": rows},
        )

    def _summary(self, section_id: str, title: str, text: str) -> ReportSection:
        return ReportSection(
            id=section_id,
            type=ReportSectionType.SUMMARY,
            title=title,
            data={"summary": text},
        )

    def _chart_placeholder(
        self, section_id: str, title: str, description: str
    ) -> ReportSection:
        return ReportSection(
            id=section_id,
            type=ReportSectionType.CHART,
            title=title,
            data={"placeholder": description},
        )

    def _document(
        self,
        context: ReportGenerationContext,
        title: str,
        report_type: ReportType,
        sections: List[ReportSection],
        generated_by: str,
    ) -> ReportDocument:
        return ReportDocument(
            id=str(uuid4()),
            title=title,
            report_type=report_type,
            generated_at=datetime.utcnow(),
            time_range=self._time_range(context),
            filters=context.filters,
            sections=sections,
            metadata=ReportMetadata(
                generated_by=generated_by,
                version="1.0",
                template_version="Phase 20",
            ),
        )

    def _base_sections(
        self, context: ReportGenerationContext, report_type: ReportType
    ) -> List[ReportSection]:
        """Leading sections every report must carry (filters + summary)."""
        return [
            self._summary(
                f"{report_type.value.lower().replace(' ', '-')}-filters",
                "Filters Applied",
                context.filters.summary(),
            )
        ]

    def _footer(
        self, context: ReportGenerationContext, report_type: ReportType
    ) -> ReportSection:
        return self._summary(
            f"{report_type.value.lower().replace(' ', '-')}-footer",
            "Report Footer",
            "Generated by Battery Intelligence Platform. " + context.filters.summary(),
        )

    def _machine_rows(self, context: ReportGenerationContext) -> List[Dict[str, Any]]:
        rows: List[Dict[str, Any]] = []
        for machine in context.machines:
            rows.append(
                {
                    "machine_id": machine.id,
                    "name": machine.name,
                    "status": machine.status,
                    "connection": machine.connection,
                    "health_score": machine.health_score,
                    "firmware": machine.firmware,
                    "last_seen": machine.last_seen.isoformat(),
                }
            )
        return rows

    def _ring_rows(self, context: ReportGenerationContext) -> List[Dict[str, Any]]:
        rows: List[Dict[str, Any]] = []
        for ring in context.rings:
            rows.append(
                {
                    "ring_id": ring.id,
                    "name": ring.name,
                    "status": ring.status,
                    "capacity_mwh": ring.capacity_mwh,
                    "installed_at": ring.installed_at.isoformat(),
                }
            )
        return rows

    def _timeline_rows(self, context: ReportGenerationContext) -> List[Dict[str, Any]]:
        rows: List[Dict[str, Any]] = []
        for event in context.timeline_events:
            rows.append(
                {
                    "event_id": event.id,
                    "timestamp": event.timestamp.isoformat(),
                    "type": event.type,
                    "machine_id": event.machine_id,
                    "message": event.message,
                }
            )
        return rows


class ExecutiveSummaryGenerator(BaseReportGenerator):
    def get_report_type(self) -> ReportType:
        return ReportType.EXECUTIVE_SUMMARY

    async def generate(
        self, context: ReportGenerationContext, generated_by: str
    ) -> ReportDocument:
        sections = self._base_sections(context, ReportType.EXECUTIVE_SUMMARY)
        sections.append(
            self._summary(
                "executive-summary-overview",
                "Executive Overview",
                (
                    f"{len(context.machines)} machine(s) tracked, "
                    f"{len(context.rings)} battery ring(s), "
                    f"{len(context.metrics)} metric(s) and "
                    f"{len(context.timeline_events)} timeline event(s) in the selected range."
                ),
            )
        )
        sections.append(
            self._metrics(
                "executive-summary-metrics",
                "Executive Summary Metrics",
                [
                    {"label": "Total Machines", "value": len(context.machines), "unit": "count"},
                    {
                        "label": "Active Machines",
                        "value": len([m for m in context.machines if m.status == "Healthy"]),
                        "unit": "count",
                    },
                    {"label": "Battery Rings", "value": len(context.rings), "unit": "count"},
                    {"label": "Timeline Events", "value": len(context.timeline_events), "unit": "count"},
                    {"label": "Tracked Metrics", "value": len(context.metrics), "unit": "count"},
                ],
            )
        )
        top = sorted(context.machines, key=lambda m: m.health_score, reverse=True)[:10]
        if top:
            sections.append(self._table("executive-summary-top-machines", "Top Machines by Health Score", self._machine_rows(context)[:10]))
        if context.rings:
            ring_summary: Dict[str, int] = {}
            for ring in context.rings:
                ring_summary[ring.name] = ring_summary.get(ring.name, 0) + 1
            sections.append(
                self._table(
                    "executive-summary-ring-summary",
                    "Ring Summary by Name",
                    [{"ring_name": name, "count": count} for name, count in sorted(ring_summary.items())],
                )
            )
        if context.timeline_events:
            sections.append(
                self._table(
                    "executive-summary-timeline",
                    "Recent Timeline Events",
                    self._timeline_rows(context)[:20],
                )
            )
        sections.append(
            self._chart_placeholder(
                "executive-summary-chart",
                "Health Score Trend",
                "Chart placeholder: fleet health score over the selected range.",
            )
        )
        sections.append(self._footer(context, ReportType.EXECUTIVE_SUMMARY))
        return self._document(
            context, "Executive Summary", ReportType.EXECUTIVE_SUMMARY, sections, generated_by
        )


class MachinePerformanceGenerator(BaseReportGenerator):
    def get_report_type(self) -> ReportType:
        return ReportType.MACHINE_PERFORMANCE

    async def generate(
        self, context: ReportGenerationContext, generated_by: str
    ) -> ReportDocument:
        sections = self._base_sections(context, ReportType.MACHINE_PERFORMANCE)

        machines = context.machines
        if context.filters.machines:
            machines = [m for m in machines if m.id in context.filters.machines]

        if not machines:
            sections.append(
                self._summary(
                    "machine-performance-no-data",
                    "No Machines Selected",
                    "No machines matched the selected filters. Adjust the machine filter and retry.",
                )
            )
        else:
            avg_health = sum(m.health_score for m in machines) / len(machines)
            sections.append(
                self._metrics(
                    "machine-performance-summary",
                    "Machine Performance Summary",
                    [
                        {"label": "Total Machines", "value": len(machines), "unit": "count"},
                        {"label": "Average Health Score", "value": round(avg_health, 1), "unit": "%"},
                        {
                            "label": "Healthy Machines",
                            "value": len([m for m in machines if m.status == "Healthy"]),
                            "unit": "count",
                        },
                        {
                            "label": "Critical Machines",
                            "value": len([m for m in machines if m.status == "Critical"]),
                            "unit": "count",
                        },
                    ],
                )
            )
            rows = [r for r in self._machine_rows(context) if r["machine_id"] in {m.id for m in machines}]
            sections.append(self._table("machine-performance-detailed", "Detailed Machine Information", rows))

            if context.rings and context.filters.rings:
                relevant = [r for r in context.rings if r.id in context.filters.rings]
                if relevant:
                    sections.append(self._table("machine-performance-rings", "Associated Battery Rings", [self._ring_row(r) for r in relevant]))

            sections.append(
                self._chart_placeholder(
                    "machine-performance-chart",
                    "Machine Performance Trend",
                    "Chart placeholder: uptime and health trend per machine.",
                )
            )
        sections.append(self._footer(context, ReportType.MACHINE_PERFORMANCE))
        return self._document(
            context, "Machine Performance", ReportType.MACHINE_PERFORMANCE, sections, generated_by
        )

    @staticmethod
    def _ring_row(ring: Any) -> Dict[str, Any]:
        return {
            "ring_id": ring.id,
            "name": ring.name,
            "status": ring.status,
            "capacity_mwh": ring.capacity_mwh,
            "installed_at": ring.installed_at.isoformat(),
        }


